#!/usr/bin/env python3
"""Write docs/CLI_REFERENCE.md: the --help text of every command-line script (kept in sync with the code).

  python scripts/make_cli_reference.py
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"render_report.py", "summarize_tests.py", "make_cli_reference.py"}     # no options (they just run)


def main():
    out = ["# Command-line reference (generated by scripts/make_cli_reference.py)", "",
           "Every script is run from the bsce folder: `python scripts/<name>.py ...` (Spyder: `%run scripts/<name>.py ...`).",
           "Scripts without options: `render_report.py` (VERIFICATION_REPORT.md -> .html), `summarize_tests.py` "
           "(test results -> tests/results/summary.md).", ""]
    for f in sorted((ROOT / "scripts").glob("*.py")):
        if f.name in SKIP:
            continue
        try:
            r = subprocess.run([sys.executable, str(f), "--help"], capture_output=True, text=True, cwd=ROOT, timeout=120)
            txt = r.stdout.strip() or r.stderr.strip()
        except subprocess.TimeoutExpired:
            txt = "(no --help output)"
        out += [f"## {f.name}", "", "```", txt, "```", ""]
    (ROOT / "docs" / "CLI_REFERENCE.md").write_text("\n".join(out), encoding="utf-8")
    print("written", ROOT / "docs" / "CLI_REFERENCE.md")


if __name__ == "__main__":
    main()
