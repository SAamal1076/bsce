"""Create derived copies of original TF references for testing (originals untouched).

reference/borgerding_py3      : Python-2 syntax converted to Python 3 (except X,e / print stmt)
reference/borgerding_py3_f64  : + float32 -> float64 (machine-precision comparisons)
reference/alista_f64          : ALISTA repo with float32 -> float64
Nothing else is changed; see CHANGES.txt in each copy.
"""
import pathlib
import re
import shutil

REF = pathlib.Path(__file__).resolve().parents[2] / "reference"


def py3(s):
    s = re.sub(r"except\s+([\w\.]+)\s*,\s*(\w+)\s*:", r"except \1 as \2:", s)
    return re.sub(r"^(\s*)print\s+('[^\n]*)$", r"\1print(\2)", s, flags=re.M)


def f64(s):
    # python-float initializers would create float32 constants -> make them float64 too
    return (s.replace("tf.float32", "tf.float64").replace("np.float32", "np.float64")
             .replace("tf.to_float(", "tf.to_double(").replace("initializer=1.0", "initializer=np.float64(1.0)"))


JOBS = [("borgerding", "borgerding_py3", [py3], "Python-2 syntax converted"),
        ("borgerding", "borgerding_py3_f64", [py3, f64], "Python-2 syntax converted; float32 -> float64"),
        ("alista", "alista_f64", [f64], "float32 -> float64")]


def main():
    for src, name, fns, msg in JOBS:
        dst = REF / name
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(REF / src, dst)
        for p in dst.rglob("*.py"):
            s = p.read_text(encoding="utf-8")
            for fn in fns:
                s = fn(s)
            p.write_text(s, encoding="utf-8")
        (dst / "CHANGES.txt").write_text(f"Generated by tests/harness/make_reference_copies.py from reference/{src}: {msg}. No other change.\n", encoding="utf-8")


if __name__ == "__main__":
    main()
